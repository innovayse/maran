//! RestorePanelSelfSigned: the panel's own certificate, replaced by a
//! freshly generated self-signed pair.

use maran_agent_core::validation::web::domain::Domain;
use maran_distro::DistroAdapter;

use crate::sites::SiteCertificate;
use crate::ssl::certificate_expiry::certificate_expiry;
use crate::ssl::key_matches_certificate::key_matches_certificate;
use crate::ssl::self_signed_marker::self_signed_marker;
use crate::ssl::self_signed_request_for::self_signed_request_for;
use crate::ssl::ssl_host::SslHost;
use crate::ssl::ssl_op_error::SslOpError;
use crate::ssl::write_material::write_material;

/// Replaces the panel's own certificate and key with a self-signed pair for
/// `host_name` (already validated by the caller) and returns the certificate's expiry as Unix seconds (issue
/// #425).
///
/// The operator asked to leave a trusted certificate behind, so the pair the
/// panel vhost names is replaced whatever it holds — a certificate an authority
/// signed included, which `generate_self_signed` would refuse to overwrite.
/// That is the difference between the two, and it is deliberate: a site's
/// placeholder is generated unattended and must never destroy a real
/// certificate, while this is an administrator's explicit request.
///
/// The write is `install_panel_certificate`'s: the generated key is checked
/// against its certificate, both files are written as ONE change of the
/// config-write protocol, validated with `nginx -t` and reloaded once, and the
/// previous pair is restored on any refusal, so a pair nginx rejects leaves the
/// panel serving what it served. The self-signed marker is written AFTER the
/// bytes it describes and never before, so it can never claim a placeholder
/// over a certificate that is still the trusted one.
///
/// Idempotent as `ssl.proto` requires: with a placeholder already installed a
/// new one is generated and replaces it, which is a replacement and not an
/// error, because the host name may have changed. The key is generated afresh
/// each call, so the bytes always differ and a reload always follows.
///
/// # Errors
///
/// Returns [`SslOpError::KeyDoesNotMatchCertificate`],
/// [`SslOpError::MalformedCertificate`], [`SslOpError::MalformedPrivateKey`] or
/// [`SslOpError::ExpiryUnreadable`] when the generated material cannot be read
/// back, before anything is written; [`SslOpError::NginxValidation`] or
/// [`SslOpError::ReloadFailed`] with the previous pair restored;
/// [`SslOpError::MaterialWrite`] for every other write failure, including the
/// marker (the placeholder is then in place without its marker, and the same
/// call converges it); and [`SslOpError::Bound`] when openssl, the validator or
/// the reload outruns its deadline.
pub fn restore_panel_self_signed(
    host: &dyn SslHost,
    distro: &dyn DistroAdapter,
    host_name: &Domain,
) -> Result<i64, SslOpError> {
    let certificate = SiteCertificate::for_panel();

    let material = host.generate_material(
        &distro.openssl_binary(),
        &self_signed_request_for(host_name, &[]),
    )?;

    // Generated by this call, so the match is expected; checked all the same,
    // because the write below cannot be undone by the next one.
    if !key_matches_certificate(host, distro, &material)? {
        return Err(SslOpError::KeyDoesNotMatchCertificate);
    }
    let expiry = certificate_expiry(host, distro, &material)?;

    write_material(host, distro, &certificate, &material)?;

    // AFTER the bytes: the file says "what is in this directory now is a
    // placeholder", so it is never written before the bytes it describes.
    host.write_self_signed_marker(&self_signed_marker(&certificate))?;

    Ok(expiry)
}

