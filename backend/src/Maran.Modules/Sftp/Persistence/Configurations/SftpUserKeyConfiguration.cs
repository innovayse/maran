using Maran.Modules.Sftp.Domain.Entities;
using Maran.Modules.Sftp.Domain.Policies;
using Maran.Modules.Sftp.Domain.ValueObjects;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Maran.Modules.Sftp.Persistence.Configurations;

/// <summary>EF Core mapping for <see cref="SftpUserKey"/> onto the <c>sftp.SftpUserKeys</c> table.</summary>
public sealed class SftpUserKeyConfiguration : IEntityTypeConfiguration<SftpUserKey>
{
    /// <summary>Configures the table, the cascade from the login, and the per-login fingerprint key.</summary>
    /// <param name="builder">The entity type builder supplied by EF Core.</param>
    public void Configure(EntityTypeBuilder<SftpUserKey> builder)
    {
        builder.ToTable("SftpUserKeys");
        builder.HasKey(key => key.Id);

        // The identity is assigned by SftpUser.AddKey, never by the store. Without this a Guid key is
        // store-generated by convention, and a row that already carries a value and is discovered
        // through its tracked login's collection is tracked as Modified (an UPDATE of a row that does
        // not exist) instead of Added.
        builder.Property(key => key.Id)
            .ValueGeneratedNever();

        builder.Property(key => key.SftpUserId)
            .IsRequired();

        builder.Property(key => key.Label)
            .IsRequired()
            .HasMaxLength(SftpKeyLimits.MaxLabelLength);

        builder.Property(key => key.PublicKey)
            .IsRequired()
            .HasMaxLength(SftpPublicKey.MaxLength);

        builder.Property(key => key.Fingerprint)
            .IsRequired()
            .HasMaxLength(SftpPublicKey.MaxFingerprintLength);

        builder.Property(key => key.Algorithm)
            .IsRequired()
            .HasMaxLength(SftpPublicKey.MaxAlgorithmLength);

        builder.Property(key => key.CreatedAt)
            .IsRequired();

        // Cascade: the keys exist for exactly as long as the login does. Deleting a login must take
        // its authenticators with it.
        builder.HasOne(key => key.SftpUser)
            .WithMany(sftpUser => sftpUser.Keys)
            .HasForeignKey(key => key.SftpUserId)
            .OnDelete(DeleteBehavior.Cascade);

        // The same key twice on one login is one credential, so the database decides it: a handler's
        // pre-check and its insert are not one atomic step, and two simultaneous adds of one key must
        // yield one row. The same key on two different logins is allowed. Leading with the login also
        // serves "this login's keys", the read every list and every key-set push makes, so EF Core
        // creates no separate index on the foreign key.
        builder.HasIndex(key => new { key.SftpUserId, key.Fingerprint })
            .IsUnique()
            .HasDatabaseName("IX_SftpUserKeys_SftpUserId_Fingerprint");
    }
}
