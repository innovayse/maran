using Maran.Modules.Sftp.Commands.AddSftpUserKey;
using Maran.Modules.Sftp.Commands.CreateSftpUser;
using Maran.Modules.Sftp.Common;
using Maran.Modules.Sftp.Models;
using Maran.Sdk.Contracts;
using Maran.Sdk.Extensions;
using Maran.Sdk.Interfaces;
using Wolverine;

namespace Maran.Modules.Sftp.Services;

/// <summary>
/// Creates an imported account's SFTP logins and authorizes their public keys (issue #127). The Sftp module's
/// <see cref="IAccountMigrationImporter"/>.
/// </summary>
/// <remarks>
/// Each login is created through <see cref="CreateSftpUserCommand"/> and each key through
/// <see cref="AddSftpUserKeyCommand"/>, so the agent's own key validation judges every key a package carries.
/// A login's password is generated by the ordinary command and returned once (decision D3). Logins live outside
/// the home, so this runs before the restore.
/// </remarks>
public sealed class SftpMigrationImporter : IAccountMigrationImporter
{
    /// <summary>The bus each login and key is created through.</summary>
    private readonly IMessageBus _bus;

    /// <summary>Creates the importer.</summary>
    /// <param name="bus">The bus each login and key is created through.</param>
    public SftpMigrationImporter(IMessageBus bus)
    {
        _bus = bus;
    }

    /// <inheritdoc />
    public string ModuleId
    {
        get { return SftpManifest.Instance.Id; }
    }

    /// <inheritdoc />
    public int Order
    {
        get { return 40; }
    }

    /// <inheritdoc />
    public Task<IReadOnlyList<MigrationFinding>> PlanAsync(
        MigrationSection section,
        MigrationPlanContext context,
        CancellationToken cancellationToken)
    {
        var readable = section.ReadPayload<SftpMigrationSection>(ModuleId, SftpMigrationExporter.SectionVersion) is not null;

        IReadOnlyList<MigrationFinding> findings = readable
            ? []
            : [new MigrationFinding(ModuleId, MigrationFindingSeverity.Conflict, MigrationCodes.SectionInvalid, context.AccountName)];

        return Task.FromResult(findings);
    }

    /// <inheritdoc />
    public async Task<Result<MigrationSectionOutcome>> ImportAsync(
        MigrationSection section,
        MigrationImportTarget target,
        CancellationToken cancellationToken)
    {
        var payload = section.ReadPayload<SftpMigrationSection>(ModuleId, SftpMigrationExporter.SectionVersion);

        if (payload is null)
        {
            return Result<MigrationSectionOutcome>.Fail(
                Error.Of(MigrationCodes.SectionInvalid, ErrorType.Validation));
        }

        if (target.AccountId is not { } accountId)
        {
            return Result<MigrationSectionOutcome>.Fail(
                Error.Of(MigrationCodes.TargetAccountMissing, ErrorType.Failure));
        }

        var secrets = new List<MigrationIssuedSecret>();

        foreach (var user in payload.Users)
        {
            var created = await _bus.InvokeAsync<Result<CreatedSftpUserDto>>(
                new CreateSftpUserCommand(accountId, user.Name),
                cancellationToken);

            if (!created.IsSuccess)
            {
                return Result<MigrationSectionOutcome>.Fail(created.Error!);
            }

            secrets.Add(new MigrationIssuedSecret(created.Value!.FullName, created.Value.Password));

            foreach (var key in user.Keys)
            {
                var added = await _bus.InvokeAsync<Result<SftpUserKeyDto>>(
                    new AddSftpUserKeyCommand(key.Label, key.PublicKey, created.Value.Id),
                    cancellationToken);

                if (!added.IsSuccess)
                {
                    return Result<MigrationSectionOutcome>.Fail(added.Error!);
                }
            }
        }

        return Result<MigrationSectionOutcome>.Ok(new MigrationSectionOutcome(null, secrets));
    }
}
