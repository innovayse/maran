using Maran.Modules.Fleet.Domain.Entities;
using Maran.Modules.Fleet.Domain.ValueObjects;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Maran.Modules.Fleet.Persistence.Configurations;

/// <summary>Maps <see cref="Server"/> onto <c>fleet.Servers</c>.</summary>
/// <remarks>
/// Read the column list for what is NOT here: no health observation (version, last seen), because those
/// are measured on the node and a stored copy is a second, staler answer; and no private key, because the
/// panel's own client identity is a different row with a different reason to be encrypted. The two unique
/// indexes are the registry's integrity: two servers cannot share a name an administrator picks them by,
/// and two rows cannot pin the same certificate, which would let one host stand as two nodes.
/// </remarks>
public sealed class ServerConfiguration : IEntityTypeConfiguration<Server>
{
    /// <summary>Configures the table, key, columns and indexes for <see cref="Server"/>.</summary>
    /// <param name="builder">The entity type builder supplied by EF Core.</param>
    public void Configure(EntityTypeBuilder<Server> builder)
    {
        // PascalCase, explicit (rules/csharp.md "Database naming: PascalCase everywhere").
        builder.ToTable("Servers");

        // The identity is chosen by the panel (the well-known local id, or a fresh one for a node),
        // never generated by the database.
        builder.HasKey(server => server.Id);
        builder.Property(server => server.Id).ValueGeneratedNever();

        builder.Property(server => server.Name)
            .IsRequired()
            .HasMaxLength(Server.NameMaxLength);

        builder.Property(server => server.Kind).IsRequired();

        builder.Property(server => server.Address)
            .HasMaxLength(Server.AddressMaxLength);

        builder.Property(server => server.Port);

        builder.Property(server => server.Fingerprint)
            .HasMaxLength(CertificateFingerprint.Length);

        builder.Property(server => server.State).IsRequired();
        builder.Property(server => server.CreatedAt).IsRequired();
        builder.Property(server => server.ApprovedAt);

        builder.HasIndex(server => server.Name)
            .IsUnique()
            .HasDatabaseName("IX_Servers_Name");

        // Partial: the local server and a node that has not enrolled yet have no fingerprint, and any
        // number of rows may be without one.
        builder.HasIndex(server => server.Fingerprint)
            .IsUnique()
            .HasFilter("\"Fingerprint\" IS NOT NULL")
            .HasDatabaseName("IX_Servers_Fingerprint");
    }
}
