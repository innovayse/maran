/// <summary>
/// The table: what the public demo does with every mutating action of every composed controller.
/// One line per action, named <c>Controller.ActionAsync</c> exactly as the architecture census spells it.
/// </summary>
/// <remarks>
/// <para>
/// <b>The stance.</b> A visitor may change resources against the simulated agent (sites, databases, cron,
/// backups, firewall ports and bans, accounts, plans, resellers). A visitor may not create or alter a
/// credential, a session, a way to sign in, mail or licence settings, the panel's certificate, the
/// security policy, an API key or the address whitelist: the shared demo logins are published, so each of
/// those would be done to every other visitor. The one place a visitor could still make a credential,
/// an account created with a password of their choosing, is closed by
/// <see cref="DemoInitialPasswordFilter"/>, because it is a value in a body and this table classifies
/// actions. The accounts, resellers and plans that hold a demo login may not be suspended, deleted,
/// transferred or re-planned either, and that is a per-resource check against
/// <see cref="DemoProtectedResources"/>. Sign-in, refresh and sign-out are allowed but draw on their own
/// allowances (<see cref="DemoSignInBudget"/>), never on the mutation budgets.
/// </para>
/// <para>
/// <b>An action missing here is refused at run time</b> and named by the census test in CI, so a new
/// endpoint is a decision someone wrote down. The table is held against the controller list by
/// <c>DemoRefusalCensusTests</c>; a reviewer reads it against
/// <c>grep -rhn "^\s*\[Http\(Post\|Put\|Patch\|Delete\)" --include=*Controller.cs backend/src/Maran.Modules</c>.
/// </para>
/// </remarks>
